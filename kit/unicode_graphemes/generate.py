#!/usr/bin/env python3
"""Generator v1: pinned Unicode 15.1.0 ranges, Python >=3.9, stdlib only.

Run from any directory; no network or host Unicode database is used.
Source URLs are https://www.unicode.org/Public/15.1.0/ucd/ plus the paths below.
"""

import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SOURCES = {
    "auxiliary/GraphemeBreakProperty.txt": "a7e52eee647e52dc210b8719b4d7037276f4b353810293d69377fc46374cec3f",
    "auxiliary/GraphemeBreakTest.txt": "ed9c5e92fd0911ccbeeb63c97cb19c519ea272ff1112ce843abd991582dd848f",
    "emoji/emoji-data.txt": "d7aef489c8fe4c14f09ea5695200277c6b93ac82ac60845cdd2161b0d6835cc1",
    "DerivedCoreProperties.txt": "f55d0db69123431a7317868725b1fcbf1eab6b265d756d1bd7f0f6d9f9ee108b",
}
GCB_VALUES = {
    "CR",
    "LF",
    "Control",
    "Extend",
    "ZWJ",
    "Regional_Indicator",
    "Prepend",
    "SpacingMark",
    "L",
    "V",
    "T",
    "LV",
    "LVT",
}


def records(name):
    for line in (ROOT / "data" / name).read_text(encoding="utf-8").splitlines():
        body = line.split("#", 1)[0].strip()
        if not body:
            continue
        span, *values = (part.strip() for part in body.split(";"))
        ends = span.split("..")
        yield int(ends[0], 16), int(ends[-1], 16), values


def compact(rows):
    result = []
    for lo, hi, value in sorted(rows):
        assert 0 <= lo <= hi <= 0x10FFFF
        if result:
            prev_lo, prev_hi, prev_value = result[-1]
            assert prev_hi < lo, "overlapping property ranges"
            if prev_hi + 1 == lo and prev_value == value:
                result[-1] = prev_lo, hi, value
                continue
        result.append((lo, hi, value))
    assert result
    return result


def generate():
    for url_path, checksum in SOURCES.items():
        path = ROOT / "data" / Path(url_path).name
        actual = hashlib.sha256(path.read_bytes()).hexdigest()
        if actual != checksum:
            raise ValueError(f"{path}: SHA-256 mismatch: {actual}")

    gcb = []
    for lo, hi, values in records("GraphemeBreakProperty.txt"):
        assert len(values) == 1 and values[0] in GCB_VALUES
        gcb.append((lo, hi, values[0]))
    ep = [
        (lo, hi, "true")
        for lo, hi, values in records("emoji-data.txt")
        if values == ["Extended_Pictographic"]
    ]
    incb = []
    for lo, hi, values in records("DerivedCoreProperties.txt"):
        if values[0] == "InCB":
            assert len(values) == 2 and values[1] in {"Consonant", "Linker", "Extend"}
            incb.append((lo, hi, values[1]))

    out = [
        "package unicode_graphemes",
        "",
        "// Generated by generate.py v1 from Unicode 15.1.0; do not edit.",
        "// Unicode data © 2023 Unicode, Inc. See data/LICENSE.txt and README.md.",
        "// Inclusive sorted disjoint ranges; omitted values are Other/false/None.",
        "",
    ]
    for name, element_type, rows, prefix in [
        ("gcb_ranges", "GCB_Range", gcb, "."),
        ("ep_ranges", "EP_Range", ep, ""),
        ("incb_ranges", "InCB_Range", incb, "."),
    ]:
        out += ["@(private)", f"{name} := [?]{element_type} {{"]
        for lo, hi, value in compact(rows):
            out.append(f"\t{{0x{lo:04X}, 0x{hi:04X}, {prefix}{value}}},")
        out += ["}", ""]
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify without writing")
    args = parser.parse_args()
    expected = generate().encode("utf-8")
    target = ROOT / "tables_generated.odin"
    if args.check:
        if target.read_bytes() != expected:
            raise SystemExit("tables_generated.odin differs; run generate.py")
        print("Unicode 15.1.0 source checksums and generated tables verified")
    else:
        target.write_bytes(expected)


if __name__ == "__main__":
    main()
